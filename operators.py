# Types of Operators

# 1. Arithmatic  operator
print("__________________________________Arithmatic  operator__________________________________")
x = 10 
y = 20
print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x//y)
print(x%y)


# 2. comparision 
print("__________________________________Comparision  operator__________________________________")
print(x==y)
print(x>=y)
print(x<=y)
print(x!=y)
print(x>y)
print(x<y)

#identity 
print("__________________________________identity  operator__________________________________")
l1 = [1,2,3,4,5]
l2 = [1,2,3,4,5]
print(l1==l2)
print(l1 in l2)

# membership 
print("__________________________________membership  operator__________________________________")
